function applyTokenFallback(input: string, tokens: PhraseMap): string {
  let output = input;
  const entries = Object.entries(tokens).sort(([a], [b]) => b.length - a.length);
  for (const [english, translated] of entries) {
    const escaped = english.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    output = output.replace(new RegExp(`\\b${escaped}\\b`, 'g'), translated);
  }
  return output;
}

export function translateUiText(input: string, language: Language): string {
  if (language === 'en') return input;
  const trimmed = input.trim();
  if (!trimmed) return input;

  const map = language === 'da' ? exactDa : exactPs;
  const exact = map[trimmed] ?? Object.entries(map).find(([key]) => key.toLocaleLowerCase() === trimmed.toLocaleLowerCase())?.[1];
  if (exact) return input.replace(trimmed, exact);

  const normalized = trimmed
    .replace(/[_-]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/\s+/g, ' ')
    .trim();
  const normalizedExact = map[normalized] ?? Object.entries(map).find(([key]) => key.toLocaleLowerCase() === normalized.toLocaleLowerCase())?.[1];
  if (normalizedExact) return input.replace(trimmed, normalizedExact);

  const tokens = language === 'da' ? tokenDa : tokenPs;
  const translated = applyTokenFallback(normalized, tokens);
  return translated === normalized ? input : input.replace(trimmed, translated);
}

export function t(language: Language, key: string): string {
  return translateUiText(key, language);
}
